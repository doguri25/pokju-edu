// Builds the game with Vite.
//   node tools/build.mjs         index.html (one file, ready for GitHub Pages) and dist/artifact.html (body only, for a Claude artifact)
//   node tools/build.mjs --dev   a Vite dev server that rebuilds when src/ or data/ changes
//
// The game is still the original set of fragments in src/: they share one function scope, so they are joined in a fixed
// order (PARTS) into one module, .build/game.js, which imports Three.js and its add-ons from npm. Vite bundles that module;
// the bundle is then inlined back into a single index.html, so the page still opens from one file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, createServer } from 'vite';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const GEN = path.join(ROOT, '.build');

// order matters: every fragment runs inside the function opened by part_start.js and closed at the end of js_gb.js.
// @spell is where data/spell.json goes in.
const PARTS = [
  'part_start.js', 'part_base.js', 'js_hill.js', 'js_world3.js', 'js_region.js', 'js_audio2.js', 'part_weapons.js', 'js_specs.js',
  'js_cars3.js', 'part_cartail.js', 'part_enemy.js', 'part_fx.js', 'js_ga.js', 'js_proj2.js', 'js_extra.js', 'js_weather.js',
  'js_modes.js', 'js_polish.js', 'js_story.js', 'js_quiz.js', '@spell', 'js_gate.js', 'js_chapters.js', 'js_link.js', 'js_fx2.js', 'js_hud2.js', 'js_gb.js'
];

// add-ons and shaders the fragments use, exposed as plain names in their shared scope
const HEADER = `// generated by tools/build.mjs from src/ and data/: edit those, not this file
import * as THREE from 'three';
import { EffectComposer } from 'three/addons/postprocessing/EffectComposer.js';
import { RenderPass } from 'three/addons/postprocessing/RenderPass.js';
import { UnrealBloomPass } from 'three/addons/postprocessing/UnrealBloomPass.js';
import { ShaderPass } from 'three/addons/postprocessing/ShaderPass.js';
import { OutputPass } from 'three/addons/postprocessing/OutputPass.js';
`;

function shaderImports() {
  const dir = path.join(SRC, 'shaders');
  if (!fs.existsSync(dir)) return { imports: '', names: {} };
  let imports = '', names = {};
  for (const f of fs.readdirSync(dir).sort()) {
    const name = 'GLSL_' + f.replace(/\W/g, '_').toUpperCase();
    imports += `import ${name} from '../src/shaders/${f}?raw';\n`;
    names[f] = name;
  }
  return { imports, names };
}

function generate() {
  fs.mkdirSync(GEN, { recursive: true });
  const sh = shaderImports();
  let js = HEADER + sh.imports;
  for (const p of PARTS) {
    if (p === '@spell') { js += '  var SPELL_DATA = ' + fs.readFileSync(path.join(ROOT, 'data', 'spell.json'), 'utf8').trim() + ';\n'; continue; }
    const f = path.join(SRC, p);
    if (!fs.existsSync(f)) continue;
    js += fs.readFileSync(f, 'utf8');
  }
  fs.writeFileSync(path.join(GEN, 'game.js'), js);
  const page = fs.readFileSync(path.join(SRC, 'page.html'), 'utf8');
  fs.writeFileSync(path.join(GEN, 'index.html'), document(page + '<script type="module" src="./game.js"></script>\n'));
}

function document(body) {
  return '<!doctype html>\n<html lang="ko">\n<head>\n<meta charset="utf-8">\n'
    + '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">\n'
    + '<style>html, body { margin: 0; height: 100%; } body { font: 14px system-ui, sans-serif; }</style>\n</head>\n<body>\n'
    + body + '</body>\n</html>\n';
}

const viteConfig = {
  root: GEN,
  base: './',
  logLevel: 'warn',
  configFile: false,
  server: { fs: { allow: [ROOT] } },
  build: { outDir: 'dist', emptyOutDir: true, target: 'es2020', chunkSizeWarningLimit: 4000, assetsInlineLimit: 100000000, modulePreload: false }
};

async function release() {
  generate();
  await build(viteConfig);
  const dist = path.join(GEN, 'dist');
  const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
  const m = html.match(/<script type="module" crossorigin src="\.\/(assets\/[^"]+\.js)"><\/script>/);
  if (!m) throw new Error('built index.html has no module script to inline');
  const code = fs.readFileSync(path.join(dist, m[1]), 'utf8').replace(/<\/script/gi, '<\\/script');
  const page = fs.readFileSync(path.join(SRC, 'page.html'), 'utf8');
  const script = '<script type="module">\n' + code + '\n</script>\n';
  fs.writeFileSync(path.join(ROOT, 'index.html'), document(page + script));
  fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'dist', 'artifact.html'), page + script);
  for (const f of ['index.html', 'dist/artifact.html']) console.log(String(fs.statSync(path.join(ROOT, f)).size).padStart(9), f);
}

async function dev() {
  generate();
  let t = null;
  for (const d of [SRC, path.join(ROOT, 'data')]) fs.watch(d, { recursive: true }, () => { clearTimeout(t); t = setTimeout(() => { generate(); console.log('rebuilt .build/game.js'); }, 80); });
  const server = await createServer({ ...viteConfig, logLevel: 'info' });
  await server.listen();
  server.printUrls();
}

(process.argv.includes('--dev') ? dev() : release()).catch((e) => { console.error(e); process.exit(1); });
